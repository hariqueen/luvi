/** 고정 공지를 위로, 그 안에서는 최신순 */
export function sortedNotices(): Notice[] {
  return [...NOTICES].sort((a, b) => {
    if (Boolean(a.pinned) !== Boolean(b.pinned)) return a.pinned ? -1 : 1;
    return b.date.localeCompare(a.date);
  });
}

export function findNotice(id: string | undefined): Notice | null {
  return NOTICES.find((n) => n.id === id) ?? null;
}

/** "2026-09-13" → "2026년 9월 13일" */
export function formatNoticeDate(date: string): string {
  const [y, m, d] = date.split('-');
  if (!y || !m || !d) return date;
  return `${y}년 ${Number(m)}월 ${Number(d)}일`;
}
